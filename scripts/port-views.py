#!/usr/bin/env python3
"""Regenerates SignetGo/Views/Ported from upstream's SwiftUI sheets.

These views are portable SwiftUI apart from a few Mac calls, so instead of hand-kept copies
that drift, each is upstream's file with mechanical substitutions. Run it after bumping the
upstream submodule, then build: a substitution that no longer matches fails loudly here, and
anything new and Mac-only fails the build.

    scripts/port-views.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "upstream" / "Signet" / "Views"
OUT = ROOT / "SignetGo" / "Views" / "Ported"

# Expert mode: multisig, baking, governance, proof of possession.
FILES = [
    "CreateMultisigSheet.swift",
    "AddMultisigSheet.swift",
    "SignMultisigSheet.swift",
    "SubmitMultisigSheet.swift",
    "BakingSheet.swift",
    "GovernanceSheet.swift",
    "EtherlinkGovernanceView.swift",
    "ProofOfPossessionSheet.swift",
    # Ledger over Bluetooth (SignetGo/Platform/LedgerBLE.swift stands in for the USB layer).
    "ConnectLedgerSheet.swift",
    # Get test tez, with the amount (within the faucet's limits).
    "FaucetSheet.swift",
]

HEADER = """// GENERATED by scripts/port-views.py from upstream/Signet/Views/{name}. Do not edit:
// change upstream (or the script) and run it again.

"""


def port(text: str) -> str:
    text = re.sub(r"^import AppKit\n", "", text, flags=re.M)
    # Pasteboard: NSPasteboard.general.clearContents(); NSPasteboard.general.setString(x, forType: .string)
    text = re.sub(r"NSPasteboard\.general\.clearContents\(\);?\s*", "", text)
    text = re.sub(r"NSPasteboard\.general\.setString\((.+?), forType: \.string\)", r"UIPasteboard.general.string = \1", text)
    text = re.sub(r"let pasteboard = NSPasteboard\.general\s*\n\s*pasteboard\.clearContents\(\)\s*\n(\s*)pasteboard\.setString\((.+?), forType: \.string\)",
                  r"\1UIPasteboard.general.string = \2", text)
    text = text.replace("NSWorkspace.shared.open(", "UIApplication.shared.open(")
    # A sheet's fixed Mac width (400 points or more) gives way to the phone's width.
    text = re.sub(r"\n(\s*)\.frame\(width: [4-9][0-9]{2}\)", "", text)
    # Forms scroll on a phone.
    text = re.sub(r"\.scrollDisabled\(true\)", "", text)
    text = text.replace(".pickerStyle(.radioGroup)", ".pickerStyle(.inline)")
    text = text.replace("Image(nsImage:", "Image(uiImage:")
    # The phone reaches a Ledger over Bluetooth, not USB (Nano X, Flex, Stax).
    text = text.replace("No Ledger found. Plug it in, unlock it and open the Tezos app.",
                        "No Ledger found. Turn on Bluetooth on your Nano X, Flex or Stax, unlock it and open the Tezos app. "
                        "The Nano S and Nano S Plus have no Bluetooth and cannot be used with an iPhone.")
    # Previews use upstream's preview fixtures; leave them out.
    text = re.sub(r"\n#Preview \{.*", "\n", text, flags=re.S)
    return text


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name in FILES:
        source = (UPSTREAM / name).read_text()
        ported = port(source)
        for mac in ("NSPasteboard", "NSWorkspace", "NSImage", "NSColor", "NSApp", "Plug it in", "USB"):
            if mac in ported:
                print(f"{name}: {mac} remains; extend port()", file=sys.stderr)
                return 1
        (OUT / name).write_text(HEADER.format(name=name) + ported)
        print(f"ported {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
